library;

import 'dart:math' as math;

/// Exception thrown when remote physical clock drift exceeds tolerated limit (24h).
class ClockDriftException implements Exception {
  final int remoteMillis;
  final int localMillis;
  final int maxDriftMillis;

  const ClockDriftException({
    required this.remoteMillis,
    required this.localMillis,
    required this.maxDriftMillis,
  });

  @override
  String toString() =>
      'ClockDriftException: excessive clock drift '
      '(remote: $remoteMillis, local: $localMillis, limit: ${maxDriftMillis}ms)';
}

/// Hybrid Logical Clock (HLC).
///
/// Combines physical time (millis) with logical counter and deterministic tie-breaking
/// by site identifier ([siteId]), ensuring strict total ordering (RN-320).
final class Hlc implements Comparable<Hlc> {
  final int millis;
  final int counter;
  final String siteId;

  /// Default maximum tolerated physical clock drift (24 hours).
  static const int defaultMaxDriftMillis = 24 * 60 * 60 * 1000;

  /// Maximum logical counter limit per millisecond (5 hex digits: 1,048,575).
  static const int maxCounter = 0xFFFFF;

  const Hlc({
    required this.millis,
    required this.counter,
    required this.siteId,
  });

  /// Creates a zero HLC associated with [siteId].
  const Hlc.zero(this.siteId) : millis = 0, counter = 0;

  /// Creates initial HLC from current physical time [nowMillis].
  Hlc.now({required this.siteId, required int nowMillis})
    : millis = nowMillis,
      counter = 0;

  /// Advances clock to record a local event with physical time [nowMillis].
  Hlc send(int nowMillis) {
    var m = math.max(millis, nowMillis);
    var c = (m == millis) ? counter + 1 : 0;
    if (c > maxCounter) {
      m += 1;
      c = 0;
    }
    return Hlc(millis: m, counter: c, siteId: siteId);
  }

  /// Updates local clock upon receiving a remote event with [remote] HLC
  /// and local physical time [nowMillis].
  ///
  /// Throws [ClockDriftException] if physical drift of [remote] exceeds [maxDriftMillis].
  Hlc receive(
    Hlc remote,
    int nowMillis, {
    int maxDriftMillis = defaultMaxDriftMillis,
  }) {
    if (remote.millis - nowMillis > maxDriftMillis) {
      throw ClockDriftException(
        remoteMillis: remote.millis,
        localMillis: nowMillis,
        maxDriftMillis: maxDriftMillis,
      );
    }

    var m = math.max(math.max(millis, nowMillis), remote.millis);
    var c = 0;
    if (m == millis && m == remote.millis) {
      c = math.max(counter, remote.counter) + 1;
    } else if (m == millis) {
      c = counter + 1;
    } else if (m == remote.millis) {
      c = remote.counter + 1;
    } else {
      c = 0;
    }
    if (c > maxCounter) {
      m += 1;
      c = 0;
    }
    return Hlc(millis: m, counter: c, siteId: siteId);
  }

  /// Packs HLC into a lexicographically sortable string.
  ///
  /// Format: `YYYY-MM-DDTHH:mm:ss.sssZ:ccccc:siteId`
  /// Where `ccccc` is 5 lowercase hexadecimal digits.
  String pack() {
    final dt = DateTime.fromMillisecondsSinceEpoch(millis, isUtc: true);
    final y = dt.year.toString().padLeft(4, '0');
    final m = dt.month.toString().padLeft(2, '0');
    final d = dt.day.toString().padLeft(2, '0');
    final h = dt.hour.toString().padLeft(2, '0');
    final min = dt.minute.toString().padLeft(2, '0');
    final s = dt.second.toString().padLeft(2, '0');
    final ms = dt.millisecond.toString().padLeft(3, '0');
    final iso = '$y-$m-${d}T$h:$min:$s.${ms}Z';
    final counterHex = counter.toRadixString(16).padLeft(5, '0');
    return '$iso:$counterHex:$siteId';
  }

  /// Reconstructs an [Hlc] from a string generated by [pack].
  static Hlc parse(String packed) {
    final zIndex = packed.indexOf('Z');
    if (zIndex == -1 ||
        zIndex + 1 >= packed.length ||
        packed[zIndex + 1] != ':') {
      throw FormatException(
        'Packed HLC missing valid timestamp separator: "$packed"',
      );
    }
    final secondColon = packed.indexOf(':', zIndex + 2);
    if (secondColon == -1) {
      throw FormatException('Packed HLC missing counter separator: "$packed"');
    }
    final iso = packed.substring(0, zIndex + 1);
    final counterHex = packed.substring(zIndex + 2, secondColon);
    final site = packed.substring(secondColon + 1);

    final millis = DateTime.parse(iso).millisecondsSinceEpoch;
    final counter = int.parse(counterHex, radix: 16);
    return Hlc(millis: millis, counter: counter, siteId: site);
  }

  @override
  int compareTo(Hlc other) {
    final cmpMillis = millis.compareTo(other.millis);
    if (cmpMillis != 0) return cmpMillis;
    final cmpCounter = counter.compareTo(other.counter);
    if (cmpCounter != 0) return cmpCounter;
    return siteId.compareTo(other.siteId);
  }

  bool operator <(Hlc other) => compareTo(other) < 0;
  bool operator <=(Hlc other) => compareTo(other) <= 0;
  bool operator >(Hlc other) => compareTo(other) > 0;
  bool operator >=(Hlc other) => compareTo(other) >= 0;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is Hlc &&
          other.millis == millis &&
          other.counter == counter &&
          other.siteId == siteId;

  @override
  int get hashCode => Object.hash(millis, counter, siteId);

  @override
  String toString() => pack();
}
