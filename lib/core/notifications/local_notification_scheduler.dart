import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import 'package:my_sweet_home/core/notifications/exact_alarm_permission_port.dart';
import 'package:my_sweet_home/core/result/result.dart';
import 'package:my_sweet_home/core/notifications/notification_scheduler_port.dart';
import 'package:my_sweet_home/core/notifications/scheduled_notification.dart';
import 'package:timezone/timezone.dart' as tz;

class LocalNotificationScheduler implements NotificationSchedulerPort {
  final FlutterLocalNotificationsPlugin _plugin;
  final ExactAlarmPermissionPort? exactAlarmPermission;
  final Iterable<Future<Result<void, Failure>> Function()> reschedulers;

  LocalNotificationScheduler(
    this._plugin, {
    this.exactAlarmPermission,
    this.reschedulers = const [],
  });

  @override
  Future<Result<void, Failure>> schedule(ScheduledNotification n) async {
    try {
      const androidDetails = AndroidNotificationDetails(
        'my_sweet_home_reminders',
        'Reminders',
        channelDescription: 'Due date reminders and notifications',
        importance: Importance.high,
        priority: Priority.high,
      );
      const iosDetails = DarwinNotificationDetails();

      const details = NotificationDetails(
        android: androidDetails,
        iOS: iosDetails,
      );

      final int notificationId = n.id.hashCode;

      // n.scheduledAt is a local date generated by ReminderPlanner.
      // Rather than from(..., tz.local) treating this as UTC instant,
      // use local date components explicitly.
      final tzDate = tz.TZDateTime(
        tz.local,
        n.scheduledAt.year,
        n.scheduledAt.month,
        n.scheduledAt.day,
        n.scheduledAt.hour,
        n.scheduledAt.minute,
        n.scheduledAt.second,
      );

      final bool canScheduleExact =
          exactAlarmPermission == null ||
          await exactAlarmPermission!.canScheduleExact();

      final scheduleMode = canScheduleExact
          ? AndroidScheduleMode.exactAllowWhileIdle
          : AndroidScheduleMode.inexactAllowWhileIdle;

      await _plugin.zonedSchedule(
        id: notificationId,
        title: n.title,
        body: n.body,
        scheduledDate: tzDate,
        notificationDetails: details,
        androidScheduleMode: scheduleMode,
      );

      return const Ok(null);
    } catch (e) {
      return Err(
        StorageFailure(detail: 'Failed to schedule notification', cause: e),
      );
    }
  }

  @override
  Future<Result<void, Failure>> cancel(String id) async {
    try {
      await _plugin.cancel(id: id.hashCode);
      return const Ok(null);
    } catch (e) {
      return Err(
        StorageFailure(detail: 'Failed to cancel notification', cause: e),
      );
    }
  }

  @override
  Future<List<ScheduledNotification>> pending() async {
    try {
      final requests = await _plugin.pendingNotificationRequests();
      return requests
          .map(
            (r) => ScheduledNotification(
              id: r.id.toString(),
              title: r.title ?? '',
              body: r.body ?? '',
              scheduledAt: DateTime.fromMillisecondsSinceEpoch(0),
            ),
          )
          .toList();
    } catch (e) {
      return [];
    }
  }

  @override
  Future<PermissionState> permission() async {
    try {
      final platform = _plugin
          .resolvePlatformSpecificImplementation<
            AndroidFlutterLocalNotificationsPlugin
          >();
      if (platform != null) {
        final hasPermission = await platform.areNotificationsEnabled();
        return hasPermission == true
            ? PermissionState.granted
            : PermissionState.denied;
      }

      final iosPlatform = _plugin
          .resolvePlatformSpecificImplementation<
            IOSFlutterLocalNotificationsPlugin
          >();
      if (iosPlatform != null) {
        final result = await iosPlatform.requestPermissions(
          alert: true,
          badge: true,
          sound: true,
        );
        return result == true
            ? PermissionState.granted
            : PermissionState.denied;
      }

      return PermissionState.denied;
    } catch (e) {
      return PermissionState.denied;
    }
  }

  @override
  Future<Result<void, Failure>> rescheduleAllAfterBoot() async {
    for (final rescheduler in reschedulers) {
      final result = await rescheduler();
      if (result.isErr) {
        return result;
      }
    }
    return const Ok(null);
  }
}
