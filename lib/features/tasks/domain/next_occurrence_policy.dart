import 'package:my_sweet_home/core/recurrence/recurrence_rule.dart';

/// PURE — determines next occurrence according to rule semantics (RN-151).
abstract interface class NextOccurrencePolicy {
  DateTime? next({
    required RecurrenceRule rule,
    required DateTime scheduledFor,
    required DateTime completedAt,
  });
}

class DefaultNextOccurrencePolicy implements NextOccurrencePolicy {
  const DefaultNextOccurrencePolicy();

  @override
  DateTime? next({
    required RecurrenceRule rule,
    required DateTime scheduledFor,
    required DateTime completedAt,
  }) {
    // To obtain internal `freq` property, we would have to use regex on rule,
    // since exposed `RecurrenceRule` does not have getters for _freq.
    // But we can check toString() representation or parse it.
    final ruleStr = rule.toString();
    final isDaily = ruleStr.contains('FREQ=DAILY');

    final baseDate = isDaily ? completedAt : scheduledFor;

    // rule.nextAfter returns next occurrence STRICTLY after instant.
    // However, baseDate could be at 10:00 and rule might be allDay, or rule
    // could be at 00:00 and completion at 14:00.
    // Para simplificar, consideramos apenas a data.
    final normalizedBaseDate = DateTime.utc(
      baseDate.year,
      baseDate.month,
      baseDate.day,
    );

    // If daily from completedAt, we need to generate next date based on completedAt,
    // but dates generated by RecurrenceRule are based on DTSTART.
    // As rule is already fixed to original task dtStart, calling nextAfter
    // in DAILY case will just skip days until past baseDate.
    // However, if we want it to be exactly N days AFTER completedAt,
    // shouldn't original DTSTART force the offset?
    // Na verdade, rule.nextAfter(normalizedBaseDate) vai manter a fase do DTSTART original.
    // If rule is "every 15 days" and dtStart was 01/01, phase will be 16/01, 31/01.
    // If completed on 10/01 (baseDate), nextAfter will give 16/01, not 25/01.
    // Therefore, RecurrenceRule `nextAfter` uses original anchor.

    // Se o requisito pede "a cada 15 dias, conta a partir de completedAt",
    // this suggests ANCHOR (DTSTART) changes. But NextOccurrencePolicy only returns date.
    // And we cannot rewrite the rule here, only determine the date!
    // Espera, NextOccurrencePolicy diz: "conta a partir de completedAt".
    // If rule is FREQ=DAILY, INTERVAL=15, and policy returns 25/03 based on completedAt (10/03),
    // como faremos?
    // Vamos simplesmente retornar completedAt.add(15 dias) se for daily?
    // But policy has to extract INTERVAL.

    // Melhor extrair o intervalo usando REGEX na string toString() se for daily.
    if (isDaily) {
      final match = RegExp(r'INTERVAL=(\d+)').firstMatch(ruleStr);
      final interval = match != null ? int.parse(match.group(1)!) : 1;
      return normalizedBaseDate.add(Duration(days: interval));
    }

    // Se for mensal, "todo dia 10", nextAfter funciona perfeitamente,
    // because phase (day 10) is recorded in rule.
    return rule.nextAfter(normalizedBaseDate);
  }
}
