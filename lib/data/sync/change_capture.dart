/// Representa um registro capturado na tabela `sync_column_versions`.
final class CapturedColumnVersion {
  final String table;
  final String rowId;
  final String column;
  final Hlc hlc;
  final String siteId;
  final String updatedAt;

  const CapturedColumnVersion({
    required this.table,
    required this.rowId,
    required this.column,
    required this.hlc,
    required this.siteId,
    required this.updatedAt,
  });

  /// Canonical column-row key.
  String get key => '$table:$rowId:$column';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is CapturedColumnVersion &&
          other.table == table &&
          other.rowId == rowId &&
          other.column == column &&
          other.hlc == hlc &&
          other.siteId == siteId;

  @override
  int get hashCode => Object.hash(table, rowId, column, hlc, siteId);

  @override
  String toString() => 'CapturedColumnVersion($key @ ${hlc.pack()} by $siteId)';
}

/// Represents a captured record in the `sync_row_tombstones` table.
final class CapturedRowTombstone {
  final String id;
  final String table;
  final String rowId;
  final Hlc hlc;
  final String purgedAt;

  const CapturedRowTombstone({
    required this.id,
    required this.table,
    required this.rowId,
    required this.hlc,
    required this.purgedAt,
  });

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is CapturedRowTombstone &&
          other.table == table &&
          other.rowId == rowId &&
          other.hlc == hlc;

  @override
  int get hashCode => Object.hash(table, rowId, hlc);

  @override
  String toString() => 'CapturedRowTombstone($table:$rowId @ ${hlc.pack()})';
}

/// Change capture and sync echo protection controller.
///
/// Manages operational states in `settings` read by SQLite triggers:
/// - `sync_applying_remote`: when `'1'`, temporarily disables change capture
///   (preventing echo of changes received from other devices).
/// - `sync_current_hlc`: allows the sync engine to define the exact HLC
///   triggers should write to the `hlc` column.
class ChangeCapture {
  final AppDatabase db;
  final Clock clock;

  ChangeCapture({required this.db, this.clock = const SystemClock()});

  /// Configuration key to suppress triggers during remote application.
  static const String applyingRemoteKey = 'sync_applying_remote';

  /// Configuration key to inject current HLC into writes.
  static const String currentHlcKey = 'sync_current_hlc';

  // ---------------------------------------------------------------------------
  // Remote Echo Guard
  // ---------------------------------------------------------------------------

  /// Enables echo protection (sets `sync_applying_remote = '1'`).
  ///
  /// When active, database write operations do NOT trigger sync triggers,
  /// preventing infinite loop duplication of remote data.
  Future<void> enableRemoteEchoGuard() async {
    await db.customStatement(
      "INSERT OR REPLACE INTO settings (key, value) VALUES ('$applyingRemoteKey', '1')",
    );
  }

  /// Disables echo protection (sets `sync_applying_remote = '0'`).
  Future<void> disableRemoteEchoGuard() async {
    await db.customStatement(
      "INSERT OR REPLACE INTO settings (key, value) VALUES ('$applyingRemoteKey', '0')",
    );
  }

  /// Checks whether echo protection is active.
  Future<bool> isApplyingRemote() async {
    final rows = await db
        .customSelect(
          "SELECT value FROM settings WHERE key = '$applyingRemoteKey'",
        )
        .get();
    if (rows.isEmpty) return false;
    return rows.first.data['value'] == '1';
  }

  /// Runs [action] under remote application context, ensuring
  /// no column versions are generated by local triggers (no echo).
  ///
  /// Supports nested calls, restoring previous state upon exit.
  Future<T> runAsRemote<T>(Future<T> Function() action) async {
    final wasActive = await isApplyingRemote();
    if (!wasActive) {
      await enableRemoteEchoGuard();
    }
    try {
      return await action();
    } finally {
      if (!wasActive) {
        await disableRemoteEchoGuard();
      }
    }
  }

  // ---------------------------------------------------------------------------
  // Controle de HLC
  // ---------------------------------------------------------------------------

  /// Sets the [hlc] to be recorded by triggers on subsequent local changes.
  /// If `null`, removes the key so triggers use current time.
  Future<void> setCurrentHlc(Hlc? hlc) async {
    if (hlc == null) {
      await db.customStatement(
        "DELETE FROM settings WHERE key = '$currentHlcKey'",
      );
    } else {
      await db.customStatement(
        "INSERT OR REPLACE INTO settings (key, value) VALUES ('$currentHlcKey', ?)",
        [hlc.pack()],
      );
    }
  }

  /// Returns the configured HLC for local changes, if any.
  Future<Hlc?> getCurrentHlc() async {
    final rows = await db
        .customSelect("SELECT value FROM settings WHERE key = '$currentHlcKey'")
        .get();
    if (rows.isEmpty) return null;
    final val = rows.first.data['value'] as String?;
    if (val == null) return null;
    return Hlc.parse(val);
  }

  /// Runs [action] explicitly associating the specified [hlc]
  /// to all local changes made within the block.
  Future<T> runWithHlc<T>(Hlc hlc, Future<T> Function() action) async {
    final previousHlc = await getCurrentHlc();
    await setCurrentHlc(hlc);
    try {
      return await action();
    } finally {
      await setCurrentHlc(previousHlc);
    }
  }

  /// Returns the highest HLC recorded in the database for [siteId], checking versions and vectors.
  Future<Hlc?> getMaxRecordedHlc(String siteId) async {
    final cvRows = await db
        .customSelect(
          'SELECT MAX(hlc) AS max_hlc FROM sync_column_versions WHERE site_id = ?',
          variables: [Variable.withString(siteId)],
        )
        .get();

    String? candidateHlc;
    if (cvRows.isNotEmpty) {
      candidateHlc = cvRows.first.data['max_hlc'] as String?;
    }

    final pvRows = await db
        .customSelect(
          'SELECT hlc FROM sync_peer_vectors WHERE site_id = ? '
          'AND household_id = (SELECT id FROM sync_household WHERE active = 1 LIMIT 1)',
          variables: [Variable.withString(siteId)],
        )
        .get();
    if (pvRows.isNotEmpty) {
      final pvHlc = pvRows.first.data['hlc'] as String?;
      if (pvHlc != null) {
        if (candidateHlc == null || pvHlc.compareTo(candidateHlc) > 0) {
          candidateHlc = pvHlc;
        }
      }
    }

    if (candidateHlc == null) return null;
    return Hlc.parse(candidateHlc);
  }

  /// Advances the local HLC using clock time and saves to `sync_current_hlc`.
  ///
  /// Ensures strict monotonicity: if physical clock regresses or if no
  /// current HLC is in settings, starts from the highest HLC already recorded by the local device.
  Future<Hlc> advanceLocalHlc({String? siteId}) async {
    final effectiveSiteId = siteId ?? (await getLocalSiteId()) ?? 'unknown';
    final currentSetting = await getCurrentHlc();
    final maxRecorded = await getMaxRecordedHlc(effectiveSiteId);

    var base = currentSetting ?? maxRecorded ?? Hlc.zero(effectiveSiteId);
    if (maxRecorded != null && maxRecorded.compareTo(base) > 0) {
      base = maxRecorded;
    }

    final advanced = base.send(clock.nowUtc().millisecondsSinceEpoch);
    await setCurrentHlc(advanced);
    return advanced;
  }

  /// Runs [action] with a new monotonically advanced HLC, restoring
  /// the prior HLC state after execution.
  Future<T> runWithNextHlc<T>(
    Future<T> Function(Hlc hlc) action, {
    String? siteId,
  }) async {
    final previousHlc = await getCurrentHlc();
    final nextHlc = await advanceLocalHlc(siteId: siteId);
    try {
      return await action(nextHlc);
    } finally {
      await setCurrentHlc(previousHlc);
    }
  }

  // ---------------------------------------------------------------------------
  // Household management and trigger activation
  // ---------------------------------------------------------------------------

  /// Checks if an active household is configured on the device.
  /// Sync triggers only fire if this method returns `true`.
  Future<bool> isHouseholdActive() async {
    final rows = await db
        .customSelect(
          'SELECT COUNT(*) AS c FROM sync_household WHERE active = 1',
        )
        .get();
    if (rows.isEmpty) return false;
    final count = rows.first.data['c'] as int? ?? 0;
    return count > 0;
  }

  /// Returns the active household ID, if any.
  Future<String?> getActiveHouseholdId() async {
    final rows = await db
        .customSelect('SELECT id FROM sync_household WHERE active = 1 LIMIT 1')
        .get();
    if (rows.isEmpty) return null;
    return rows.first.data['id'] as String?;
  }

  /// Returns the local site ID of this device in the active household.
  Future<String?> getLocalSiteId() async {
    final rows = await db
        .customSelect(
          'SELECT local_site_id FROM sync_household WHERE active = 1 LIMIT 1',
        )
        .get();
    if (rows.isEmpty) return null;
    return rows.first.data['local_site_id'] as String?;
  }

  /// Activates a sync household on this device for change capture.
  Future<void> activateHousehold({
    required String householdId,
    required String name,
    required String localSiteId,
    List<SyncArea> sharedAreas = const [
      SyncArea.catalog,
      SyncArea.home,
      SyncArea.finance,
    ],
  }) async {
    final nowIso = clock.nowUtc().toIso8601String();
    final areasJoined = sharedAreas.map((a) => a.name).join(',');

    // Deactivate any previously active household to ensure at most 1 active household
    await db.customStatement(
      'UPDATE sync_household SET active = 0 WHERE active = 1',
    );

    await db.customStatement(
      '''
      INSERT OR REPLACE INTO sync_household
      (id, name, local_site_id, shared_areas, created_at, joined_at, active)
      VALUES (?, ?, ?, ?, ?, ?, 1)
      ''',
      [householdId, name, localSiteId, areasJoined, nowIso, nowIso],
    );
  }

  /// Deactivates the current household (so triggers no longer record versions).
  Future<void> deactivateHousehold() async {
    await db.customStatement(
      'UPDATE sync_household SET active = 0 WHERE active = 1',
    );
  }

  // ---------------------------------------------------------------------------
  // Captured sync metadata queries
  // ---------------------------------------------------------------------------

  /// Returns versions recorded in `sync_column_versions`, with optional filters.
  Future<List<CapturedColumnVersion>> getCapturedVersions({
    String? tableName,
    String? rowId,
    String? columnName,
  }) async {
    final conditions = <String>[];
    final variables = <Variable>[];

    if (tableName != null) {
      conditions.add('table_name = ?');
      variables.add(Variable.withString(tableName));
    }
    if (rowId != null) {
      conditions.add('row_id = ?');
      variables.add(Variable.withString(rowId));
    }
    if (columnName != null) {
      conditions.add('column_name = ?');
      variables.add(Variable.withString(columnName));
    }

    final whereClause = conditions.isEmpty
        ? ''
        : 'WHERE ${conditions.join(' AND ')}';
    final rows = await db
        .customSelect(
          'SELECT table_name, row_id, column_name, hlc, site_id, updated_at '
          'FROM sync_column_versions $whereClause ORDER BY hlc ASC',
          variables: variables,
        )
        .get();

    return rows.map((r) {
      return CapturedColumnVersion(
        table: r.data['table_name'] as String,
        rowId: r.data['row_id'] as String,
        column: r.data['column_name'] as String,
        hlc: Hlc.parse(r.data['hlc'] as String),
        siteId: r.data['site_id'] as String,
        updatedAt: r.data['updated_at'] as String,
      );
    }).toList();
  }

  /// Returns tombstones recorded in `sync_row_tombstones`.
  Future<List<CapturedRowTombstone>> getCapturedTombstones({
    String? tableName,
    String? rowId,
    Hlc? sinceHlc,
  }) async {
    final conditions = <String>[];
    final variables = <Variable>[];

    if (tableName != null) {
      conditions.add('table_name = ?');
      variables.add(Variable.withString(tableName));
    }
    if (rowId != null) {
      conditions.add('row_id = ?');
      variables.add(Variable.withString(rowId));
    }
    if (sinceHlc != null) {
      conditions.add('hlc > ?');
      variables.add(Variable.withString(sinceHlc.pack()));
    }

    final whereClause = conditions.isEmpty
        ? ''
        : 'WHERE ${conditions.join(' AND ')}';
    final rows = await db
        .customSelect(
          'SELECT id, table_name, row_id, hlc, purged_at '
          'FROM sync_row_tombstones $whereClause ORDER BY hlc ASC',
          variables: variables,
        )
        .get();

    return rows.map((r) {
      return CapturedRowTombstone(
        id: r.data['id'] as String,
        table: r.data['table_name'] as String,
        rowId: r.data['row_id'] as String,
        hlc: Hlc.parse(r.data['hlc'] as String),
        purgedAt: r.data['purged_at'] as String,
      );
    }).toList();
  }

  /// Counts how many column versions are recorded.
  Future<int> countCapturedVersions() async {
    final rows = await db
        .customSelect('SELECT COUNT(*) AS c FROM sync_column_versions')
        .get();
    if (rows.isEmpty) return 0;
    return rows.first.data['c'] as int? ?? 0;
  }

  /// Counts how many tombstones are recorded.
  Future<int> countCapturedTombstones() async {
    final rows = await db
        .customSelect('SELECT COUNT(*) AS c FROM sync_row_tombstones')
        .get();
    if (rows.isEmpty) return 0;
    return rows.first.data['c'] as int? ?? 0;
  }

  /// Clears all recorded column versions (used in tests or resets).
  Future<void> clearCapturedVersions() async {
    await db.customStatement('DELETE FROM sync_column_versions');
  }

  /// Clears all recorded tombstones.
  Future<void> clearCapturedTombstones() async {
    await db.customStatement('DELETE FROM sync_row_tombstones');
  }
}
